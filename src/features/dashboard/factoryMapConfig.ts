/**
 * Phân loại màu trạng thái theo Health Score (Chỉ số an toàn)
 * Quy tắc hiển thị chuẩn:
 * - 90–100%: Xanh lá (#16A34A) - An toàn
 * - 80% đến dưới 90%: Vàng (#EAB308) - Theo dõi
 * - 70% đến dưới 80%: Cam (#F97316) - Cảnh báo
 * - Dưới 70%: Đỏ (#DC2626) - Nguy hiểm
 * - Không có dữ liệu / null / undefined / NaN / ngoài 0-100: Xám (#94A3B8) - Chưa giám sát
 */
export function getHealthScoreColor(score: number | null | undefined): string {
  if (score === null || score === undefined || typeof score !== 'number' || isNaN(score)) {
    return '#94A3B8';
  }
  if (score < 0 || score > 100) {
    return '#94A3B8';
  }
  if (score >= 90) {
    return '#16A34A';
  }
  if (score >= 80) {
    return '#EAB308';
  }
  if (score >= 70) {
    return '#F97316';
  }
  return '#DC2626';
}

/**
 * Phân loại màu trạng thái theo Trạng thái vận hành thiết bị/khu vực
 */
export function getStatusDotColor(status?: string | null): string {
  if (!status) return '#94A3B8';
  const s = status.toUpperCase();
  if (s === 'RUNNING' || s === 'NORMAL' || s === 'OK') return '#16A34A';
  if (s === 'WARNING') return '#EAB308';
  if (s === 'STOPPED' || s === 'CRITICAL') return '#DC2626';
  return '#94A3B8';
}

